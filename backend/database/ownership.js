function getOwnership(entityType) {
    const key = String(entityType || '').trim().toLowerCase();
    const aliases = {
        users: 'user',
        resumes: 'resume',
        portfolios: 'portfolio',
        covers: 'cover',
        jobs: 'job',
        applications: 'application',
        memberships: 'membership',
        subscriptions: 'subscription',
        payment_orders: 'payment_order',
        system_settings: 'settings',
        roles: 'role',
        permissions: 'permission',
        custom_pages: 'settings',
    };
    const resolved = aliases[key] || key;
    return ENTITIES[resolved] || {
        entity: resolved,
        mariadb: true,
        firestore: true,
        authoritative: 'mariadb',
        syncDirection: 'BIDIRECTIONAL',
        writeMode: 'MULTI_WRITER',
        consistency: 'EVENTUAL',
        conflict: 'VERSION',
        idField: 'id',
        versionField: 'revision',
        dateFields: [],
        tombstoneOnDelete: true,
        notes: 'Default contract for unlisted entities.',
    };
}

function ownershipMatrix() {
    return Object.values(ENTITIES).map((row) => ({
        Entity: row.entity,
        MariaDB: row.mariadb ? 'Yes' : 'No',
        Firestore: row.firestore ? 'Yes' : 'No',
        AuthoritativeSource: row.authoritative,
        SyncDirection: row.syncDirection,
        WriteMode: row.writeMode,
        Conflict: row.conflict,
        Deletion: row.tombstoneOnDelete ? 'tombstone' : 'none',
    }));
}

