/**
 * Explicit dual-database ownership contract.
 *
 * MariaDB is the default primary. Firestore is the secondary / operational
 * fallback. Ownership is per-entity, never implied by whichever adapter a
 * route happens to call.
 *
 * Write modes:
 *   SINGLE_OWNER  — only the authoritative engine accepts writes; the other
 *                   is updated asynchronously via the durable outbox.
 *   MULTI_WRITER  — both engines may accept writes during failover; conflicts
 *                   are resolved by monotonic revision + mutation sequence.
 *
 * Deletion: tombstone + mutation event. A missing document is NEVER treated
 * as "recreate me".
 */

