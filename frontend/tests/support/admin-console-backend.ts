/**
 * A deterministic stand-in for the two backend answers the admin console needs.
 *
 * ## Why this exists
 *
 * Every console gate in `tests/admin-console-ux.spec.ts` — five device classes, axe, keyboard
 * traversal, 44 px boxes, visual baselines, Core Web Vitals — used to depend on a live backend
 * *and* MariaDB, because the console renders nothing until it has a session and a capability
 * census. In the remediation sandbox neither exists, so the whole file timed out on
 * `getByRole('tablist')` and the console shipped with **no** browser evidence at all.
 *
 * That was an environment limit turned into a product gap. It is not one: the console's
 * behaviour is a function of two responses, and both can be served deterministically.
 *
 * | Request | Answer | Why this is faithful |
 * |---|---|---|
 * | `GET /api/users-data/profile` | `200 {success:true}` | `verifyPreviewSession` only reads the status code to decide valid / invalid / unknown (`lib/preview-session.ts:167-176`) |
 * | `GET /api/me/capabilities` | a committed fixture generated by the backend's own `resolveCapabilities()` | `scripts/gen-capabilities-fixture.mjs`; re-generated by `npm run gen:fixtures` and checked by `npm run verify:fixtures` |
 * | every other `/api/**` | `503` with the platform's error envelope | the tabs must render their *unavailable* data state; asserting a layout against invented row data would prove nothing about the layout an operator actually sees when the store is down |
 *
 * ## What it deliberately does not do
 *
 * It does not fake a *permission decision*. Authority is the backend's answer, generated from
 * the backend's resolver from the backend's literal role bundle — the client never decides. A
 * test that wanted to prove "an AUDITOR cannot see Operations" would use the AUDITOR fixture and
 * assert the tab is absent, which is exactly what the console does with the real answer.
 *
 * @module tests/support/admin-console-backend
 */

import { readFileSync } from 'node:fs';

import type { Page } from '@playwright/test';

/**
 * Fixtures are read from disk rather than `import`ed: Node's ESM loader requires an
 * `import { … } with { type: 'json' }` attribute for JSON, which Playwright's transform does not
 * emit, and a `require` would tie the spec to CommonJS. A file read has neither problem and the
 * path resolves relative to this module, not the cwd.
 */
function fixture(role: string): CapabilityFixture {
  return JSON.parse(readFileSync(new URL(`../fixtures/me-capabilities.${role}.json`, import.meta.url), 'utf8')) as CapabilityFixture;
}

/** One tab as the console receives it. */
interface CapabilityTab {
  id: string;
  label: string;
  group: string;
  allowed: boolean;
  superAdminOnly: boolean;
  reason: string | null;
  missing: string[];
}

/** `GET /api/me/capabilities` as the backend fixture generates it. */
export interface CapabilityFixture {
  success: true;
  role: string;
  tabs: CapabilityTab[];
  actions: Record<string, Record<string, boolean>>;
  defaultTab: string | null;
  permissions: string[];
  authority: { source: string; degraded: boolean; roles: number };
}

/** Fixtures by the role the console expects in the preview session. */
/** The configuration census, from `GET /api/admin/config` via the backend's `describeConfig`. */
export const CONFIG_CENSUS: unknown = JSON.parse(
  readFileSync(new URL('../fixtures/config-census.json', import.meta.url), 'utf8'),
);

export const CAPABILITY_FIXTURES = {
  SUPER_ADMIN: fixture('SUPER_ADMIN'),
  ADMIN: fixture('ADMIN'),
  AUDITOR: fixture('AUDITOR'),
} as const;

/** Roles the capability fixtures cover. */
export type FixtureRole = keyof typeof CAPABILITY_FIXTURES;

/**
 * Any role a preview session may carry, including ones with no admin capability at all.
 * `previewToken` only encodes the claim; the *authority* decision is the backend's, and a
 * `USER` session is a legitimate thing for a lifecycle test to hold.
 */
export type PreviewRole = FixtureRole | 'USER';

/** The identity a console test runs as. */
export interface ConsoleIdentity {
  uid: string;
  email: string;
  displayName: string;
  role: PreviewRole;
}

/**
 * Build a well-formed, unexpired preview-session token.
 *
 * The browser cannot verify the HMAC and does not try: `decodePreviewToken` checks only the
 * shape, the decoded payload and the expiry (`lib/preview-session.ts:46-75`). The signature is
 * therefore 64 hex characters of filler, and the security property is unchanged — the token is
 * a *candidate* until `verifyPreviewSession` confirms it with the server, which this module
 * stubs only for the duration of a test.
 *
 * @param identity who to sign in as
 * @param ttlSeconds how long the token stays valid
 * @returns `rptest.<base64url payload>.<64 hex>`
 */
export function previewToken(identity: ConsoleIdentity, ttlSeconds = 3_600): string {
  const payload = {
    uid: identity.uid,
    email: identity.email,
    role: identity.role,
    exp: Math.floor(Date.now() / 1_000) + ttlSeconds,
  };
  const encoded = Buffer.from(JSON.stringify(payload), 'utf8')
    .toString('base64')
    .replace(/\+/g, '-')
    .replace(/\//g, '_')
    .replace(/=+$/, '');
  return `rptest.${encoded}.${'a'.repeat(64)}`;
}

/** The platform's error envelope, so the tabs exercise their real failure path. */
const UNAVAILABLE = JSON.stringify({
  success: false,
  error: { code: 'STORE_UNAVAILABLE', message: 'The configuration store is unreachable in this test.', requestId: 'fixture' },
});

/**
 * Serve the two answers the console needs and an honest failure for everything else.
 *
 * Registration order matters: Playwright matches the **last** registered route first, so the
 * catch-all goes first and the specific answers after it.
 *
 * @param page the page under test
 * @param role which capability fixture to answer with
 */
export async function installConsoleBackend(page: Page, role: PreviewRole): Promise<void> {
  await page.route('**/api/**', (route) =>
    route.fulfill({ status: 503, contentType: 'application/json', body: UNAVAILABLE }),
  );
  await page.route('**/api/users-data/profile', (route) =>
    route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify({ success: true, data: {} }) }),
  );
  // A role with no fixture (e.g. `USER`) gets the empty answer: no tabs, which is what the
  // backend returns for a caller with no admin capability at all.
  const capabilities = role in CAPABILITY_FIXTURES ? CAPABILITY_FIXTURES[role as FixtureRole] : { ...CAPABILITY_FIXTURES.AUDITOR, role, tabs: CAPABILITY_FIXTURES.AUDITOR.tabs.map((tab) => ({ ...tab, allowed: false, reason: 'missing-permission' })), defaultTab: null };
  await page.route('**/api/me/capabilities', (route) =>
    route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(capabilities) }),
  );
  // The configuration census is a real registered payload, not an invented row: it is produced
  // by the backend's own `describeConfig` (see the generator), so the provenance labels the
  // console renders are the ones the registry actually declares.
  await page.route('**/api/admin/config', (route) =>
    route.fulfill({ status: 200, contentType: 'application/json', body: JSON.stringify(CONFIG_CENSUS) }),
  );
}

/**
 * Seed the preview session and install the stubbed backend.
 *
 * @param page the page under test
 * @param identity who to sign in as (defaults to a super-admin, because the baselines should
 *   capture every tab; a partial strip is a separate, role-specific assertion)
 */
export async function authenticateConsole(page: Page, identity?: Partial<ConsoleIdentity>): Promise<ConsoleIdentity> {
  const resolved: ConsoleIdentity = {
    uid: 'fixture-super-admin',
    email: 'admin@ime365.com',
    displayName: 'Sarah Administrator',
    role: 'SUPER_ADMIN' as PreviewRole,
    ...identity,
  };
  const token = previewToken(resolved);
  await page.addInitScript(
    ([stored, user]) => {
      localStorage.setItem(stored as string, JSON.stringify(user));
    },
    ['ime_dev_user', { ...resolved, token }] as const,
  );
  await installConsoleBackend(page, resolved.role);
  return resolved;
}
