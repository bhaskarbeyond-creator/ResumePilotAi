/**
 * Generate an authoritative configuration census directly from source.
 *
 * The census is derived, never hand-maintained, so it cannot drift from the
 * code the way the previous hand-written matrices did. It also flags backend
 * configuration that has no Super Admin / Admin surface, which is the class of
 * "capability exists but is not reachable" gap this audit is hunting.
 */
import fs from 'node:fs';
import path from 'node:path';

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === 'node_modules' || entry.name === 'dist' || entry.name === '.git') continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else out.push(full);
  }
  return out;
}

const SECRET_HINT = /(SECRET|TOKEN|KEY|PASSWORD|CREDENTIAL|PRIVATE|SALT|WEBHOOK)/i;
const FLAG_HINT = /(ENABLED|DISABLED|_FLAG|FEATURE_)/i;
const TEST_HINT = /(TEST|MOCK|FIXTURE)/i;

function classify(name, { frontend, backend }) {
  const tags = [];
  // A VITE_*/import.meta.env value is compiled into the client bundle and is
  // therefore readable by anyone who loads the page. Labelling it SECRET is
  // actively misleading — it implies a protection that cannot exist. These are
  // publishable client identifiers (Firebase Web API key, Maps key, …) whose
  // security comes from provider-side referrer/domain restrictions, NOT secrecy.
  // The VITE_ prefix is the determinant, not which files happen to read the
  // value. Vite inlines every VITE_* variable into the client bundle, so such a
  // key is public even when a build script also reads it from process.env
  // (VITE_FIREBASE_KEY is exactly this case).
  const buildTimePublic = name.startsWith('VITE_') || (frontend && !backend);
  if (frontend) tags.push('BUILD TIME');
  if (buildTimePublic && SECRET_HINT.test(name)) tags.push('PUBLISHABLE CLIENT IDENTIFIER');
  else if (SECRET_HINT.test(name)) tags.push('SECRET');
  if (FLAG_HINT.test(name)) tags.push('FEATURE FLAG');
  if (TEST_HINT.test(name)) tags.push('TEST ONLY');
  if (backend && !frontend && !tags.includes('SECRET')) tags.push('INFRASTRUCTURE ONLY');
  if (!tags.length) tags.push('READ ONLY');
  return tags;
}

const SELF = 'scripts/generate-config-census.mjs';
const files = [...walk('backend'), ...walk('src'), ...walk('scripts')]
  .filter(f => /\.(m?js|jsx|cjs)$/.test(f))
  // The generator's own source contains the very patterns it scans for, which
  // would otherwise inject phantom keys (e.g. a bare `NAME`) into the census.
  .filter(f => f.split(path.sep).join('/') !== SELF);
const census = new Map();

for (const file of files) {
  const source = fs.readFileSync(file, 'utf8');
  const isFrontend = file.startsWith('src' + path.sep);
  for (const match of source.matchAll(/process\.env\.([A-Z0-9_]+)/g)) record(match[1], file, isFrontend);
  for (const match of source.matchAll(/process\.env\[['"]([A-Z0-9_]+)['"]\]/g)) record(match[1], file, isFrontend);
  for (const match of source.matchAll(/import\.meta\.env\.([A-Z0-9_]+)/g)) record(match[1], file, true);
  // Modules that take an injected `env` object (defaulting to process.env) read
  // configuration as `env.NAME`. The first census pass matched only
  // `process.env.NAME` and therefore missed FIREBASE_TOTP_MFA_ENABLED entirely —
  // a key the platform's own security posture depends on.
  for (const match of source.matchAll(/\benv(?:ironment)?\.([A-Z][A-Z0-9_]{3,})\b/g)) record(match[1], file, isFrontend);
  for (const match of source.matchAll(/\benv(?:ironment)?\[['"]([A-Z][A-Z0-9_]{3,})['"]\]/g)) record(match[1], file, isFrontend);
}

function record(name, file, frontend) {
  if (!census.has(name)) census.set(name, { name, files: new Set(), frontend: false, backend: false });
  const entry = census.get(name);
  entry.files.add(file);
  if (frontend) entry.frontend = true;
  else entry.backend = true;
}

// Which settings are reachable from an Admin/Super Admin surface?
const adminSurface = [...walk('src/components/admin'), ...walk('src/enterprise')]
  .filter(f => /\.jsx?$/.test(f))
  .map(f => fs.readFileSync(f, 'utf8'))
  .join('\n');
const platformConfigSource = fs.existsSync('backend/services/platformConfiguration.js')
  ? fs.readFileSync('backend/services/platformConfiguration.js', 'utf8')
  : '';

const rows = [...census.values()].sort((a, b) => a.name.localeCompare(b.name)).map(entry => {
  const tags = classify(entry.name, entry);
  const surfacedInUi = adminSurface.includes(entry.name);
  const surfacedInConfigApi = platformConfigSource.includes(entry.name);
  return { ...entry, tags, surfacedInUi, surfacedInConfigApi, files: [...entry.files].sort() };
});

const unsurfacedBackend = rows.filter(r => r.backend && !r.frontend && !r.surfacedInUi && !r.surfacedInConfigApi && !r.tags.includes('TEST ONLY'));

const lines = [];
lines.push('# Configuration Census (generated)');
lines.push('');
lines.push(`Generated by \`scripts/generate-config-census.mjs\` from source. Do not edit by hand.`);
lines.push('');
lines.push(`- Total distinct configuration keys: **${rows.length}**`);
lines.push(`- Backend-only keys with no Admin/Super Admin surface: **${unsurfacedBackend.length}**`);
lines.push(`- Keys classified SECRET: **${rows.filter(r => r.tags.includes('SECRET')).length}**`);
lines.push(`- Keys classified FEATURE FLAG: **${rows.filter(r => r.tags.includes('FEATURE FLAG')).length}**`);
lines.push('');
lines.push('## Full inventory');
lines.push('');
lines.push('| Key | Scope | Classification | Exposed in Admin UI | Exposed via platform configuration API | Declared in |');
lines.push('| --- | --- | --- | --- | --- | --- |');
for (const row of rows) {
  const scope = row.frontend && row.backend ? 'frontend + backend' : row.frontend ? 'frontend (build time)' : 'backend';
  lines.push(`| \`${row.name}\` | ${scope} | ${row.tags.join(', ')} | ${row.surfacedInUi ? 'yes' : 'no'} | ${row.surfacedInConfigApi ? 'yes' : 'no'} | ${row.files.slice(0, 3).map(f => `\`${f}\``).join(', ')}${row.files.length > 3 ? ` (+${row.files.length - 3})` : ''} |`);
}
lines.push('');
lines.push('## Backend configuration with no Admin/Super Admin surface');
lines.push('');
lines.push('These are operator/infrastructure controls. They are listed so the gap is explicit rather than assumed; a key appearing here is not automatically a defect, but it cannot be changed without a redeploy.');
lines.push('');
for (const row of unsurfacedBackend) lines.push(`- \`${row.name}\` — ${row.tags.join(', ')}`);
lines.push('');

fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync('docs/CONFIGURATION_CENSUS.md', lines.join('\n'));
console.log(`Wrote docs/CONFIGURATION_CENSUS.md with ${rows.length} keys (${unsurfacedBackend.length} backend-only without a UI surface).`);
