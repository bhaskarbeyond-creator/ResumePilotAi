#!/usr/bin/env node
/**
 * DIR-040 — Regenerates the mod_headers block of every Apache config from the
 * single canonical policy in scripts/security-headers-policy.mjs.
 *
 * Why a generator instead of three hand-maintained copies: the three configs
 * already disagreed with each other (the root .htaccess was missing the rsms.me
 * font origins present in the built copies), and a security policy that can
 * silently drift between environments is not enforcing anything. Only the
 * mod_headers block is owned here — each file keeps its own mod_rewrite rules,
 * which legitimately differ between the dev root, public/, and dist/ trees.
 *
 * Usage:  node scripts/generate-security-headers.mjs          (write)
 *         node scripts/generate-security-headers.mjs --check  (verify, exit 1)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { renderApacheHeaderBlock } from './security-headers-policy.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
// dist/ is a gitignored build artifact: it is regenerated by `npm run build`, so a
// missing dist/.htaccess is not drift and must not fail a fresh clone.
const REQUIRED_TARGETS = ['.htaccess', 'public/.htaccess'];
const OPTIONAL_TARGETS = ['dist/.htaccess'];
const TARGETS = [...REQUIRED_TARGETS, ...OPTIONAL_TARGETS];
const BLOCK = /<IfModule mod_headers\.c>[\s\S]*?<\/IfModule>/;

function rewrite(source) {
  if (!BLOCK.test(source)) {
    throw new Error('no <IfModule mod_headers.c> block found; refusing to guess its position');
  }
  return source.replace(BLOCK, renderApacheHeaderBlock());
}

const check = process.argv.includes('--check');
let drift = 0;

for (const target of TARGETS) {
  const absolute = path.join(root, target);
  if (!fs.existsSync(absolute)) {
    if (OPTIONAL_TARGETS.includes(target)) {
      console.log(`SKIP     ${target} (build artifact not present)`);
      continue;
    }
    console.error(`MISSING  ${target}`);
    drift += 1;
    continue;
  }
  const current = fs.readFileSync(absolute, 'utf8');
  const next = rewrite(current);
  if (next === current) {
    console.log(`OK       ${target}`);
    continue;
  }
  if (check) {
    console.error(`DRIFT    ${target} — run: node scripts/generate-security-headers.mjs`);
    drift += 1;
    continue;
  }
  fs.writeFileSync(absolute, next, 'utf8');
  console.log(`UPDATED  ${target}`);
}

if (drift > 0) {
  console.error(`\n${drift} file(s) out of sync with the canonical policy.`);
  process.exit(1);
}
if (check) console.log('\nAll Apache configs match the canonical security header policy.');
