/**
 * DIR-031 — Single source of truth for the STATIC public discovery documents
 * (public/robots.txt and public/sitemap.xml).
 *
 * WHY THIS EXISTS
 * Before this module both static documents hardcoded `https://ai-resume-builder.local`
 * — a placeholder host that `backend/services/publicAppUrl.js` explicitly classifies
 * as a placeholder (`isPlaceholderHost` rejects any `.local` host). Production crawlers
 * were therefore handed a sitemap of URLs on a host that does not exist, which is the
 * single most damaging SEO defect the audit found: a valid sitemap index that points
 * at unreachable URLs degrades to "all pages are broken" rather than "no sitemap".
 *
 * WHY A GENERATOR INSTEAD OF TWO HAND-EDITED FILES
 * The live /sitemap.xml is generated by the backend
 * (backend/services/publicSitemap.js, proxied by public/.htaccess). The static file is
 * the build-time fallback that answers when the backend is unreachable, so the two must
 * list the SAME paths. Two hand-maintained lists had already drifted silently. The path
 * list is therefore imported from the backend's own STABLE_PUBLIC_PATHS rather than
 * copied, so parity is structural instead of aspirational.
 *
 * ORIGIN PROVENANCE — no domain is invented here.
 * CANONICAL_PUBLIC_ORIGIN is `airesume.projectdemo.guru`, which this repository already
 * declares as its authoritative release host in docs/SAFE_PRODUCTION_WORKFLOW.md
 * (`PRODUCTION_URL`, and "This is the authoritative release path for ..."). A deployment
 * on a different host overrides it with PUBLIC_APP_URL / APP_PUBLIC_URL /
 * CANONICAL_PUBLIC_URL at generation time; a placeholder or loopback host is REFUSED
 * rather than written, mirroring publicAppUrl.js `assertUsableOrigin`.
 */

/** Authoritative release origin, sourced from docs/SAFE_PRODUCTION_WORKFLOW.md. */
export const CANONICAL_PUBLIC_ORIGIN = 'https://airesume.projectdemo.guru';

/**
 * Paths that must never be crawled. Every entry is a private or noindex namespace
 * already declared in src/components/RouteSeo.jsx `PRIVATE_PREFIXES`, so this list
 * cannot contradict the page-level robots meta tags.
 */
export const DISALLOWED_ROBOTS_PATHS = Object.freeze([
  '/dashboard',
  '/dashboard2',
  '/build-resume',
  '/create-resume',
  '/resume',
  '/coverletter',
  '/cover-letter',
  '/adm',
  '/admin',
  '/platform',
  '/org',
  '/enterprise',
  '/employer',
  '/blog-editor',
  '/portfolio/builder',
  '/export',
  '/shared',
  '/front',
  '/login',
]);

function normalizeOrigin(value) {
  try {
    const parsed = new URL(String(value || '').trim());
    if (parsed.protocol !== 'https:') return '';
    if (parsed.username || parsed.password || parsed.search || parsed.hash) return '';
    if (parsed.pathname && parsed.pathname !== '/') return '';
    return parsed.origin;
  } catch {
    return '';
  }
}

/**
 * Rejects placeholder and loopback hosts exactly as publicAppUrl.js does, so a build
 * cannot regress the sitemap back to a `.local` placeholder.
 */
export function isUnusableDiscoveryHost(hostname) {
  const host = String(hostname || '').trim().toLowerCase().split(':')[0];
  if (!host) return true;
  if (host === 'localhost' || host === '127.0.0.1' || host === '0.0.0.0' || host === '::1') return true;
  if (host.endsWith('.localhost') || host.endsWith('.local') || host.endsWith('.internal')) return true;
  if (host.endsWith('.example') || host.endsWith('.invalid') || host.endsWith('.test')) return true;
  return ['example.com', 'example.org', 'example.net', 'invalid', 'local'].includes(host);
}

/**
 * Resolves the origin for the static discovery documents.
 *
 * Order: an explicitly configured real HTTPS origin, else the documented canonical
 * release origin. A configured origin that is a placeholder/loopback host is IGNORED
 * (not written) so that a misconfigured build environment degrades to the documented
 * production host instead of leaking a placeholder to crawlers.
 */
export function resolveDiscoveryOrigin(env = {}) {
  const explicit = normalizeOrigin(
    env.PUBLIC_APP_URL || env.APP_PUBLIC_URL || env.CANONICAL_PUBLIC_URL || ''
  );
  if (explicit && !isUnusableDiscoveryHost(new URL(explicit).hostname)) return explicit;
  return CANONICAL_PUBLIC_ORIGIN;
}

/** Renders the complete robots.txt body. */
export function renderPublicRobotsTxt(origin = CANONICAL_PUBLIC_ORIGIN) {
  const resolved = normalizeOrigin(origin) || CANONICAL_PUBLIC_ORIGIN;
  const lines = [
    'User-agent: *',
    'Allow: /',
    ...DISALLOWED_ROBOTS_PATHS.map((path) => `Disallow: ${path}`),
    `Sitemap: ${resolved}/sitemap.xml`,
  ];
  return `${lines.join('\n')}\n`;
}

/**
 * Renders sitemap.xml from the backend's own stable path list.
 *
 * The URL shapes are produced by backend/services/publicSitemap.js `buildPublicSitemapXml`
 * so the static fallback and the live route are byte-compatible for the stable routes.
 */
export function renderPublicSitemapXml(paths, origin = CANONICAL_PUBLIC_ORIGIN) {
  const resolved = normalizeOrigin(origin) || CANONICAL_PUBLIC_ORIGIN;
  const uniquePaths = [...new Set(paths)];
  const urls = uniquePaths.map((path) => `  <url><loc>${new URL(path, `${resolved}/`).href}</loc></url>`);
  return `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join('\n')}\n</urlset>\n`;
}