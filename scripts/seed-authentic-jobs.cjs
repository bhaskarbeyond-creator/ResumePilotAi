async function seed() {
  const pool = getPool();
  console.log('Seeding authentic job postings into MariaDB `jobs` table...');

  for (const job of AUTHENTIC_JOBS) {
    await pool.query(
      `INSERT INTO jobs 
        (id, employer_id, company_name, company_logo, title, description, requirements, skills, location, 
         job_type, workplace_type, salary_min, salary_max, salary_currency, experience_level, status, 
         applicants_count, featured, expires_at, created_at, updated_at, revision)
       VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, DATE_ADD(CURRENT_TIMESTAMP, INTERVAL 60 DAY), CURRENT_TIMESTAMP, CURRENT_TIMESTAMP, 1)
       ON DUPLICATE KEY UPDATE 
         company_name = VALUES(company_name),
         title = VALUES(title),
         description = VALUES(description),
         requirements = VALUES(requirements),
         skills = VALUES(skills),
         location = VALUES(location),
         job_type = VALUES(job_type),
         workplace_type = VALUES(workplace_type),
         salary_min = VALUES(salary_min),
         salary_max = VALUES(salary_max),
         salary_currency = VALUES(salary_currency),
         experience_level = VALUES(experience_level),
         status = VALUES(status),
         featured = VALUES(featured),
         updated_at = CURRENT_TIMESTAMP`,
      [
        job.id, 'OhZdiSIFL7ePA1TMkfu9bnR935D3', job.company_name, job.company_logo, job.title, job.description,
        job.requirements, job.skills, job.location, job.job_type, job.workplace_type,
        job.salary_min, job.salary_max, job.salary_currency, job.experience_level,
        job.status, job.applicants_count, job.featured
      ]
    );
  }

  const [countRows] = await pool.query('SELECT COUNT(*) AS total, COUNT(DISTINCT company_name) AS companies FROM jobs WHERE status = "active"');
  console.log(`✅ Successfully seeded authentic jobs! Active postings in database: ${countRows[0].total} across ${countRows[0].companies} top companies.`);
  process.exit(0);
}

seed().catch(err => {
  console.error('Seeding failed:', err);
  process.exit(1);
});
